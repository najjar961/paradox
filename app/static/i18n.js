  const params = new URLSearchParams(location.search);
  const wanted = (params.get("lang") || "").toLowerCase();
  const browser = (navigator.languages || [navigator.language || "en"]).map((l) => String(l).slice(0, 2).toLowerCase());
  let lang = ["de", "en"].includes(wanted) ? wanted : (browser.find((l) => l === "de" || l === "en") || "en");
  const listeners = [];
  const squash = (s) => s.replace(/\s+/g, " ").trim();

  function t(key, vars) {
    if (key == null) return "";
    let s = (lang === "de" && DE[key]) || key;
    if (s.includes("|")) {
      const [one, other] = s.split("|");
      s = vars && vars.n === 1 ? one : other;
    }
    return vars ? s.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : s;
  }

  // Elements marked in the HTML: data-i18n (text), data-i18n-html (trusted markup from
  // this file only), data-i18n-attr="placeholder,title,aria-label". English is kept in
  // data-en* so switching back works.
  function apply(root) {
    root = root || document;
    document.documentElement.lang = lang;
    root.querySelectorAll("[data-i18n]").forEach((el) => {
      if (el.dataset.en == null) el.dataset.en = squash(el.textContent);
      el.textContent = t(el.dataset.en);
    });
    root.querySelectorAll("[data-i18n-html]").forEach((el) => {
      if (el.dataset.enHtml == null) el.dataset.enHtml = squash(el.innerHTML);
      el.innerHTML = t(el.dataset.enHtml);
    });
    root.querySelectorAll("[data-i18n-attr]").forEach((el) => {
      for (const a of el.dataset.i18nAttr.split(",")) {
        const key = "en" + a.replace(/(^|-)(\w)/g, (m, d, c) => c.toUpperCase());
        if (el.dataset[key] == null) el.dataset[key] = el.getAttribute(a) || "";
        el.setAttribute(a, t(el.dataset[key]));
      }
    });
  }

  function set(l) {
    if (!["de", "en"].includes(l) || l === lang) return;
    lang = l;
    const url = new URL(location.href);
    url.searchParams.set("lang", l);
    history.replaceState(history.state, "", url);
    apply(document);
    listeners.forEach((f) => f(l));
  }

  window.i18n = {
    t, apply, set,
    get lang() { return lang; },
    onChange(f) { listeners.push(f); },
    has(key) { return key in DE; },
  };
